def main() -> None:
    rng = random.Random(42)
    rows: list[dict[str, str]] = []
    for family, (category, variants) in FAMILIES.items():
        assert len(variants) == 5, family
        for test_name, message, log in variants:
            rows.append({
                "test_name": test_name,
                "message": message,
                "log": log,
                "category": category,
                "template_family": family,
            })
    for test_name, message, log, category, family in HARD:
        rows.append({
            "test_name": test_name,
            "message": message,
            "log": log,
            "category": category,
            "template_family": family,
        })
    rng.shuffle(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["test_name", "message", "log", "category", "template_family"])
        w.writeheader()
        w.writerows(rows)
    from collections import Counter
    print(f"Wrote {len(rows)} rows to {OUT}")
    print("By category:", dict(Counter(r["category"] for r in rows)))
    print("Families:", len({r["template_family"] for r in rows}))


